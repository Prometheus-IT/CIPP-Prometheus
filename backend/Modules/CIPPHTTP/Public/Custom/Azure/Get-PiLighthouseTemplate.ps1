function Get-PiLighthouseTemplate {
    <#
    .SYNOPSIS
        Builds the Azure Lighthouse onboarding ARM template with this CIPP instance's values filled in.
    .DESCRIPTION
        Fork addition (Prometheus Informatik). ARM JSON equivalent of
        fork/lighthouse/cipp-avd-lighthouse.bicep, with managedByTenantId and cippPrincipalId
        set as parameter defaults so a customer administrator can deploy it without typing ids.
        Resource names use the same guid() inputs as the Bicep file, so deploying either one
        again updates the existing offer instead of adding a second one.

        Deploy per customer subscription, signed in to the CUSTOMER tenant with Owner (or
        another role allowed to create Lighthouse assignments) on that subscription.
    .FUNCTIONALITY
        Internal
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)]
        [string]$ManagedByTenantId,

        [Parameter(Mandatory = $true)]
        [string]$PrincipalId,

        [string]$PrincipalDisplayName = 'CIPP AVD Management'
    )

    $Parsed = [guid]::Empty
    foreach ($Value in @($ManagedByTenantId, $PrincipalId)) {
        if (-not [guid]::TryParse($Value, [ref]$Parsed)) { throw "Lighthouse template: '$Value' is not a valid id." }
    }

    $Authorizations = foreach ($Role in Get-PiLighthouseRoles) {
        [ordered]@{
            principalId            = "[parameters('cippPrincipalId')]"
            principalIdDisplayName = "[parameters('cippPrincipalDisplayName')]"
            roleDefinitionId       = $Role.Id
        }
    }

    return [ordered]@{
        '$schema'      = 'https://schema.management.azure.com/schemas/2018-05-01/subscriptionDeploymentTemplate.json#'
        contentVersion = '1.0.0.0'
        metadata       = [ordered]@{
            description = 'Prometheus CIPP AVD Azure Lighthouse delegation. Generated by CIPP; equivalent to fork/lighthouse/cipp-avd-lighthouse.bicep.'
        }
        parameters     = [ordered]@{
            managedByTenantId        = [ordered]@{
                type         = 'string'
                defaultValue = $ManagedByTenantId
                metadata     = @{ description = 'Partner (managing) tenant id - the tenant CIPP runs in.' }
            }
            cippPrincipalId          = [ordered]@{
                type         = 'string'
                defaultValue = $PrincipalId
                metadata     = @{ description = 'Object id in the partner tenant of the CIPP SAM service principal, or of a group that contains it.' }
            }
            cippPrincipalDisplayName = [ordered]@{
                type         = 'string'
                defaultValue = $PrincipalDisplayName
                metadata     = @{ description = 'Display name shown to the customer for the delegated principal.' }
            }
            offerName                = [ordered]@{
                type         = 'string'
                defaultValue = 'Prometheus Informatik - CIPP AVD Management'
                metadata     = @{ description = "Offer name shown in the customer's Service providers blade." }
            }
            offerDescription         = [ordered]@{
                type         = 'string'
                defaultValue = 'Read access plus AVD session host, user session and VM power operations for managed Azure Virtual Desktop.'
                metadata     = @{ description = 'Offer description shown to the customer.' }
            }
        }
        variables      = [ordered]@{
            definitionName = "[guid(parameters('offerName'), parameters('managedByTenantId'))]"
            assignmentName = "[guid(parameters('offerName'), parameters('managedByTenantId'), subscription().subscriptionId)]"
        }
        resources      = @(
            [ordered]@{
                type       = 'Microsoft.ManagedServices/registrationDefinitions'
                apiVersion = '2022-10-01'
                name       = "[variables('definitionName')]"
                properties = [ordered]@{
                    registrationDefinitionName = "[parameters('offerName')]"
                    description                = "[parameters('offerDescription')]"
                    managedByTenantId          = "[parameters('managedByTenantId')]"
                    authorizations             = @($Authorizations)
                }
            }
            [ordered]@{
                type       = 'Microsoft.ManagedServices/registrationAssignments'
                apiVersion = '2022-10-01'
                name       = "[variables('assignmentName')]"
                dependsOn  = @("[subscriptionResourceId('Microsoft.ManagedServices/registrationDefinitions', variables('definitionName'))]")
                properties = [ordered]@{
                    registrationDefinitionId = "[subscriptionResourceId('Microsoft.ManagedServices/registrationDefinitions', variables('definitionName'))]"
                }
            }
        )
        outputs        = [ordered]@{
            registrationDefinitionId = [ordered]@{
                type  = 'string'
                value = "[subscriptionResourceId('Microsoft.ManagedServices/registrationDefinitions', variables('definitionName'))]"
            }
            registrationAssignmentId = [ordered]@{
                type  = 'string'
                value = "[subscriptionResourceId('Microsoft.ManagedServices/registrationAssignments', variables('assignmentName'))]"
            }
        }
    }
}
